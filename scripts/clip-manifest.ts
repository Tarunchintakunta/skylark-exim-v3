import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import type { Plugin } from 'vite'
import { chaptersFor } from '../src/config/chapters'

/** the film's clip tiers (segments.ts FILM_W: 720 on phones, else 1280 or 1920) */
const TIERS = [720, 1280, 1920] as const
const OUT = new URL('../src/film/manifest.ts', import.meta.url)
const media = (f: string) => new URL(`../public/media/${f}`, import.meta.url)
const hash = (buf: Buffer) => createHash('sha256').update(buf).digest('hex').slice(0, 10)

/**
 * src/film/manifest.ts (#251): every clip of each path in story order, with its chapter, its place in the chapter, and per
 * tier the byte size and a short content hash. The hash goes on the URL (`?v=`), so /media/*.mp4 can be cached immutably
 * and a re-encoded clip is still picked up. Rewritten on every build (only when it changed); committed, so typecheck runs
 * without a build.
 */
export function manifestSource() {
  const paths = (['ocean', 'pond'] as const).map((path) => {
    const clips = chaptersFor(path).flatMap((ch, chapter) => {
      const videos = ch.media.filter((m) => m.kind === 'video')
      return videos.map((m, seg) => {
        const files = TIERS.map((w) => {
          const f = media(`${m.id}_${w}.mp4`)
          if (!existsSync(f)) throw new Error(`clip-manifest: missing public/media/${m.id}_${w}.mp4`)
          const buf = readFileSync(f)
          return `${w}: { bytes: ${buf.length}, v: '${hash(buf)}' }`
        })
        return `    { id: '${m.id}', chapter: ${chapter}, seg: ${seg}, of: ${videos.length}, tiers: { ${files.join(', ')} } },`
      })
    })
    return `  ${path}: [\n${clips.join('\n')}\n  ],`
  })
  const versions = readdirSync(media(''))
    .filter((f) => f.endsWith('.mp4'))
    .sort()
    .map((f) => `  '${f.replace(/\.mp4$/, '')}': '${hash(readFileSync(media(f)))}',`)
  return `// Generated by scripts/clip-manifest.ts from src/config/chapters.ts and public/media. Do not edit.
export interface ClipFile {
  bytes: number
  v: string
}
export interface Clip {
  id: string
  /** chapter index in the path's chapter list */
  chapter: number
  /** this clip's place among the chapter's clips, and how many it has */
  seg: number
  of: number
  tiers: Record<720 | 1280 | 1920, ClipFile>
}

export const CLIPS: Record<'ocean' | 'pond', Clip[]> = {
${paths.join('\n')}
}

/** content hash of every public/media/*.mp4, keyed by '<id>_<tier>'; segments.ts clipUrl puts it on the URL */
export const MP4_V: Record<string, string> = {
${versions.join('\n')}
}
`
}

export function clipManifest(): Plugin {
  return {
    name: 'clip-manifest',
    buildStart() {
      const next = manifestSource()
      if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== next) writeFileSync(OUT, next)
    },
  }
}
